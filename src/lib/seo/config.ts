// Site-level SEO constants + the business NAP in structured form. Single home of the
// global defaults (Pierre's decision: code-level defaults, no `siteSettings` singleton —
// see ADR 0025). The FLAT display strings stay in `@/content/legal/identity.ts` (éditeur)
// and `@/content/contactPage.ts` (geo); this module derives the SEO/structured-data shapes
// from them so there is a single source for the raw values.

/**
 * Canonical site origin — server-resolved, no trailing slash. Prefer a non-`NEXT_PUBLIC_`
 * `SITE_URL` (Coolify runtime var — the CLAUDE.md prefix rule: server-injected values must
 * not be inlined at build), fall back to the existing `NEXT_PUBLIC_SITE_URL` (already read
 * by robots/sitemap) then the prod domain. This is THE single source for the origin — robots
 * and sitemap import it too.
 */
export const SITE_URL = (
	process.env.SITE_URL ??
	process.env.NEXT_PUBLIC_SITE_URL ??
	"https://estuaire.fr"
).replace(/\/+$/, "");

/** Public brand name (what appears in tabs / social cards / titles). */
export const SITE_NAME = "Estuaire";

/** Open Graph locale. */
export const SITE_LOCALE = "fr_FR";

