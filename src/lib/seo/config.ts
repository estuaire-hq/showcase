/** Build a site-absolute URL from a root-relative path (idempotent on absolute URLs). */
export function absoluteUrl(path = "/"): string {
	if (/^https?:\/\//.test(path)) return path;
	return `${SITE_URL}${path.startsWith("/") ? path : `/${path}`}`;
}
